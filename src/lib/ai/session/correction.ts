// 부정·중단 감지 — **잘못 들어간 대화에서 나오는 길** (2026-08-03)
//
// 없어서 생긴 일: 세금을 물었더니 기부 대화가 열렸고, 사용자가
// "아니 세금인데 뭔 고향에 기부야"라고 **명시적으로 부정했는데도** 다음 턴이
// "어느 지역에 마음을 두고 계신가요?"였다. 그만하겠다고 해도 마찬가지였다.
// 한 번 들어가면 대화로는 못 나오는 구조였다.
//
// 왜 규칙(코드)인가. "사용자가 방금 부정했다"는 판정을 모델에게 맡기면, 모델이
// 슬롯을 채우려는 관성에 눌려 그냥 지나간다 — 실제로 프롬프트 규칙 10이 이미
// "되물었으면 먼저 답하라"고 적혀 있는데도 지나갔다. 부정은 대화의 흐름을 바꾸는
// **제어 신호**라 코드가 잡아야 한다 (guide 층과 같은 이유).
//
// express-detect와의 경계: 저쪽은 "무엇을 하고 싶은가"(의사), 여기는
// "지금 이 흐름이 틀렸다"(정정). 반대 방향이라 한 표에 넣지 않는다.

export type Correction =
  /** 그만두겠다 — 가지를 닫고 코드가 답한다. 모델을 부르지 않는다 */
  | { kind: "STOP" }
  /** 지금 흐름이 틀렸다 — 가지는 두되 슬롯 질문을 멈추고 무엇을 원하는지 먼저 묻는다 */
  | { kind: "CORRECT" }
  | { kind: "NONE" };

/** 그만두겠다는 말. "안 할래요"·"됐어요"·"그만"·"취소" */
const STOP =
  /(그만할|그만하|그만두|안\s*할래|안\s*하고\s*싶|하기\s*싫|됐어요|됐습니다|관두|취소할래|나갈래|그만)/;

/** 흐름을 부정·정정하는 말. 문두의 "아니"가 대표형이다.
 *  ⚠ "아니요"만 잡으면 안 된다 — 실제 발화는 "아니 세금인데 뭔 고향에 기부야"였다.
 *    부정어가 문장 **앞**에 오고 뒤에 하고 싶은 말이 붙는 것이 한국어의 정정 꼴이다. */
const CORRECT =
  /(^\s*(아니|아뇨|아니요|아닌데|그게\s*아니|그런\s*게\s*아니|틀렸))|((이|가|은|는)?\s*아니라)|(말고)|(잘못\s*(알|이해|들))|(왜\s*(자꾸|계속))|(뭔\s*소리)|(딴\s*소리)/;

/**
 * 사용자가 지금 흐름을 멈추거나 되돌리려 하는가.
 *
 * STOP이 CORRECT보다 우선한다 — "아니 그만할래요"는 정정이 아니라 중단이다.
 * 둘 다 아니면 NONE: 대화는 하던 대로 간다 (감지가 대화를 방해하지 않는다).
 */
export function detectCorrection(text: string): Correction {
  if (STOP.test(text)) return { kind: "STOP" };
  if (CORRECT.test(text)) return { kind: "CORRECT" };
  return { kind: "NONE" };
}

/**
 * 정정할 때 코드가 내는 답.
 *
 * **왜 모델에게 맡기지 않는가.** 프롬프트에 "지금 사용자가 방향이 틀렸다고 하니
 * 준비된 질문을 하지 마라"를 명령형으로 넣고도 Solar는 두 번 다 슬롯을 물었다
 * (2026-08-03 실측). 슬롯을 채우려는 관성이 한 줄의 지시보다 강하다.
 * 안내(guide)·중단(STOP)과 같은 결론이다 — **대화의 방향을 바꾸는 말은 코드가 답한다.**
 *
 * 짧게 끝내는 것이 중요하다. 여기서 길게 설명하면 그 자체가 또 하나의 어긋난 말이 된다.
 * 사용자가 다시 말하면 그 발화는 안내·가지 판정을 처음부터 다시 거친다.
 */
export const CORRECT_REPLY =
  "제가 잘못 알아들었습니다. 죄송합니다. " +
  "무엇을 도와드리면 될지 다시 한번 말씀해 주시겠어요? 원하지 않으시는 것은 권해 드리지 않겠습니다.";

/** 중단할 때 코드가 내는 답. 재촉하지 않고, 되돌아올 길만 남긴다 (P4) */
export const STOP_REPLY =
  "네, 여기서 멈추겠습니다. 지금까지 말씀하신 내용은 그대로 저장해 두었으니 " +
  "언제든 다시 이어가실 수 있어요. 다른 것이 궁금하시면 편하게 말씀해 주세요.";
