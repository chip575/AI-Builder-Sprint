// 대화 화면의 **사용 설명** — 이 챗봇이 무엇을 하고, 무엇을 하지 않는가.
//
// 왜 화면에 적어 두는가. 대화창은 무엇이든 물어봐도 될 것처럼 보인다. 그래서
// 사용자는 상속세 계산이나 이혼 재산분할까지 묻고, 답이 "문의처로 가세요"면
// 서비스가 고장 난 것으로 읽는다. **경계를 미리 말해 두면 거절이 안내가 된다.**
//
// 왜 한 파일인가. 여기 적힌 "답하는 것"은 안내층(guide.ts)이 실제로 답하는 목록이고,
// "답하지 않는 것"은 프롬프트의 LIMITS와 같은 내용이다. 화면마다 따로 적으면
// 코드가 바뀌어도 설명은 옛말로 남는다 — 실제로 그런 어긋남을 여러 번 겪었다.
//
// ⚠ 수치를 쓰지 않는다 (P3). 공제율·기한은 lib/rules의 몫이고, 여기서는
//   "어디서 그 값을 보실 수 있는지"까지만 말한다.

export interface ChatbotGuide {
  /** 이 화면의 대화가 하는 일 — 한 줄 */
  purpose: string;
  /** 어떻게 쓰면 되는지 — 실제로 해 보실 말 */
  howTo: string[];
  /** 답해 드리는 것 */
  answers: string[];
  /** 답하지 않는 것. 이유까지 적는다 — 이유 없는 거절은 고장으로 읽힌다 */
  declines: string[];
}

