  "규칙:",
  "1. **질문은 정확히 하나만 한다.** 물음표는 답변 전체에서 한 번만 쓴다 — 여러 개를 물으면 사용자가 무엇에 답할지 몰라 대화가 끊긴다.",
  "2. 금액·수증자·기부처를 네가 먼저 제안하지 않는다. 사용자가 정한다.",
