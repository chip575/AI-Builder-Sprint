// 시스템 프롬프트 — **모델에게 나가는 말의 유일한 출처** (FR-101 · P3 · P4)
//
// 왜 어댑터에서 떼어냈나: `solar-responder.ts`는 *HTTP를 어떻게 부르나*이고 여기는
// *무엇을 말하나*다. 한 파일에 있으면 둘 중 하나를 고칠 때마다 다른 하나를 읽어야 하고,
// 프롬프트가 바뀌었는지가 어댑터 diff에 묻힌다.
//
// 왜 코드인가 (DB·원격 설정이 아니라): 프롬프트를 런타임에 고칠 수 있게 하면
//   ① gate:check의 "프롬프트 안의 법률 수치" 검사가 아무것도 검사하지 않게 되고 (절대규칙 2)
//   ② 모델의 행동이 **git diff 없이** 바뀐다 — 병합 전 사람 리뷰를 통째로 우회한다.
// 프롬프트는 코드다. 코드처럼 다룬다.
//
// ⚠ 여기에 숫자를 쓰지 않는다. 공제율·한도·기한은 lib/rules가 갖고 화면이 계산한다 (P3).
// ⚠ 문구를 고치면 __snapshots__ diff를 함께 본다 — 조각이 아니라 **조립 결과**가 리뷰 대상이다.
import type { BranchType } from "../../contracts/common";

export interface PromptInput {
  /** Express·감지로 열린 가지. null이면 축(회상 인터뷰) */
  branchType: BranchType | null;
  /** 세션이 이미 아는 값 — 다시 묻지 않게 넘긴다 */
  knownFacts: { key: string; value: string | number }[];
  /** 아직 비어 있는 필수 슬롯 */
  missingRequired: string[];
  /** 축 세션에서 다음에 던질 회상 질문 (lib/rules/question-bank). 가지면 null */
  nextAxisQuestion: string | null;
}

const NL = "\n";

/** ① 말투·대화 규칙 — 가지·문서와 무관하게 항상 붙는다 */
